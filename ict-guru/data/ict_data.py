# Helper function to get data by topic
def get_data_by_topic(topic_name):
    return [item for item in ict_data if item["topic"].lower() == topic_name.lower()]

# Helper function to search by keyword
def search_data(keyword):
    keyword = keyword.lower()
    results = []
    for item in ict_data:
        if (keyword in item["question"].lower() or 
            keyword in item["answer"].lower() or
            keyword in item["topic"].lower() or
            any(keyword in tag.lower() for tag in item["tags"])):
            results.append(item)
    return results